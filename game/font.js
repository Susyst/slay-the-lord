const FONT_H = 9;

function textWidth(s) {
  let w = 0;
  for (const ch of s) { const gl = GLYPHS[ch] || GLYPHS["?"]; w += gl.w + 1; }
  return Math.max(0, w - 1);
}

// Draw text with the GBA two-tone look: ink plus a lighter drop shadow down-right.
function drawText(ctx, s, x, y, ink = INK, shadow = INK_SH) {
  for (const pass of shadow ? [0, 1] : [1]) {
    ctx.fillStyle = pass ? ink : shadow;
    let cx = Math.round(x) + (pass ? 0 : 1);
    const cy = Math.round(y) + (pass ? 0 : 1);
    for (const ch of s) {
      const gl = GLYPHS[ch] || GLYPHS["?"];
      gl.rows.forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) if (row[rx] === "#") ctx.fillRect(cx + rx, cy + gl.top + ry, 1, 1);
      });
      cx += gl.w + 1;
    }
  }
}

function wrapText(s, maxW) {
  const out = [];
  for (const para of s.split("\n")) {
    let line = "";
    for (const word of para.split(" ")) {
      const t = line ? line + " " + word : word;
      if (textWidth(t) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}
